
-- PetroPulse PostgreSQL schema
-- Keep the original Oracle scripts unchanged.

CREATE TABLE IF NOT EXISTS pp_users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(254) NOT NULL UNIQUE,
    full_name VARCHAR(100) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    token_version INTEGER NOT NULL DEFAULT 0,
    is_demo SMALLINT NOT NULL DEFAULT 0 CHECK (is_demo IN (0, 1)),
    achievement_threshold NUMERIC(5,2) NOT NULL DEFAULT 85
        CHECK (achievement_threshold >= 0 AND achievement_threshold <= 100),
    downtime_threshold_hours NUMERIC(5,2) NOT NULL DEFAULT 8
        CHECK (downtime_threshold_hours >= 0 AND downtime_threshold_hours <= 24),
    repeat_miss_count INTEGER NOT NULL DEFAULT 3 CHECK (repeat_miss_count > 0),
    missing_record_days INTEGER NOT NULL DEFAULT 2 CHECK (missing_record_days > 0),
    target_at_risk_pct NUMERIC(5,2) NOT NULL DEFAULT 90
        CHECK (target_at_risk_pct >= 0 AND target_at_risk_pct <= 100),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS pp_wells (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES pp_users(id),
    well_code VARCHAR(20) NOT NULL,
    well_name VARCHAR(100) NOT NULL,
    field_name VARCHAR(100) NOT NULL,
    well_type VARCHAR(20) NOT NULL DEFAULT 'VERTICAL'
        CHECK (well_type IN ('VERTICAL', 'HORIZONTAL', 'DEVIATED')),
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE'
        CHECK (status IN ('ACTIVE', 'INACTIVE', 'MAINTENANCE')),
    description VARCHAR(500),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_pp_wells_user_code UNIQUE (user_id, well_code),
    CONSTRAINT uq_pp_wells_id_user UNIQUE (id, user_id)
);

CREATE TABLE IF NOT EXISTS pp_production (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES pp_users(id),
    well_id BIGINT NOT NULL,
    production_date DATE NOT NULL,
    planned_oil NUMERIC(14,2) NOT NULL CHECK (planned_oil >= 0),
    actual_oil NUMERIC(14,2) NOT NULL CHECK (actual_oil >= 0),
    oil_price NUMERIC(10,2) NOT NULL CHECK (oil_price >= 0),
    operating_cost NUMERIC(14,2) NOT NULL DEFAULT 0
        CHECK (operating_cost >= 0),
    downtime_hours NUMERIC(4,1) NOT NULL DEFAULT 0
        CHECK (downtime_hours >= 0 AND downtime_hours <= 24),
    loss_category VARCHAR(30),
    notes VARCHAR(500),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_pp_production_well_owner
        FOREIGN KEY (well_id, user_id)
        REFERENCES pp_wells(id, user_id),
    CONSTRAINT uq_pp_production_well_date UNIQUE (well_id, production_date)
);

CREATE TABLE IF NOT EXISTS pp_targets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES pp_users(id),
    well_id BIGINT NOT NULL,
    daily_target_oil NUMERIC(14,2) NOT NULL CHECK (daily_target_oil > 0),
    start_date DATE NOT NULL,
    end_date DATE,
    notes VARCHAR(300),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_pp_targets_dates
        CHECK (end_date IS NULL OR end_date >= start_date),
    CONSTRAINT fk_pp_targets_well_owner
        FOREIGN KEY (well_id, user_id)
        REFERENCES pp_wells(id, user_id)
);

CREATE TABLE IF NOT EXISTS pp_alerts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES pp_users(id),
    well_id BIGINT,
    record_id BIGINT REFERENCES pp_production(id),
    rule_code VARCHAR(30) NOT NULL,
    severity VARCHAR(10) NOT NULL
        CHECK (severity IN ('LOW', 'MEDIUM', 'HIGH', 'CRITICAL')),
    message VARCHAR(300) NOT NULL,
    trigger_reason VARCHAR(500),
    alert_date DATE NOT NULL DEFAULT CURRENT_DATE,
    status VARCHAR(20) NOT NULL DEFAULT 'NEW'
        CHECK (status IN ('NEW', 'ACKNOWLEDGED', 'RESOLVED', 'DISMISSED')),
    dedupe_key VARCHAR(120) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_pp_alerts_user_dedupe UNIQUE (user_id, dedupe_key)
);

CREATE INDEX IF NOT EXISTS ix_prod_user_date
    ON pp_production(user_id, production_date);

CREATE INDEX IF NOT EXISTS ix_prod_well
    ON pp_production(well_id);

CREATE INDEX IF NOT EXISTS ix_wells_user
    ON pp_wells(user_id);

CREATE INDEX IF NOT EXISTS ix_tgt_well
    ON pp_targets(well_id);

CREATE INDEX IF NOT EXISTS ix_alert_user
    ON pp_alerts(user_id);

CREATE INDEX IF NOT EXISTS ix_alert_rec
    ON pp_alerts(record_id);
