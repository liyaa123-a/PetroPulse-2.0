-- PetroPulse 2.0 | 01_schema.sql | DDL: table creation
-- Run as the APPLICATION schema user (e.g. PETROPULSE_APP), never as ADMIN.
-- Units: oil = barrels (bbl), prices = USD per bbl, costs = USD, downtime = hours.
-- NOT destructive: re-running fails with ORA-00955 instead of replacing tables.
-- Keys, foreign keys, unique/check constraints and indexes are added in 02_constraints_indexes.sql.

CREATE TABLE pp_users (
    id                        NUMBER        GENERATED BY DEFAULT ON NULL AS IDENTITY,
    email                     VARCHAR2(254) NOT NULL,
    full_name                 VARCHAR2(100) NOT NULL,
    password_hash             VARCHAR2(255) NOT NULL,          -- salted scrypt hash, never the password
    token_version             NUMBER(10)    DEFAULT 0 NOT NULL, -- bumped on logout / password change to revoke tokens
    is_demo                   NUMBER(1)     DEFAULT 0 NOT NULL,
    achievement_threshold     NUMBER(5,2)   DEFAULT 85 NOT NULL, -- alert when achievement % is below this
    downtime_threshold_hours  NUMBER(5,2)   DEFAULT 8  NOT NULL,
    repeat_miss_count         NUMBER(3)     DEFAULT 3  NOT NULL,
    missing_record_days       NUMBER(3)     DEFAULT 2  NOT NULL,
    target_at_risk_pct        NUMBER(5,2)   DEFAULT 90 NOT NULL,
    created_at                TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    updated_at                TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE pp_wells (
    id          NUMBER        GENERATED BY DEFAULT ON NULL AS IDENTITY,
    user_id     NUMBER        NOT NULL,
    well_code   VARCHAR2(20)  NOT NULL,
    well_name   VARCHAR2(100) NOT NULL,
    field_name  VARCHAR2(100) NOT NULL,
    well_type   VARCHAR2(20)  DEFAULT 'VERTICAL' NOT NULL,
    status      VARCHAR2(20)  DEFAULT 'ACTIVE'   NOT NULL,
    description VARCHAR2(500),
    created_at  TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    updated_at  TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE pp_production (
    id              NUMBER        GENERATED BY DEFAULT ON NULL AS IDENTITY,
    user_id         NUMBER        NOT NULL,
    well_id         NUMBER        NOT NULL,
    production_date DATE          NOT NULL,
    planned_oil     NUMBER(14,2)  NOT NULL,   -- bbl
    actual_oil      NUMBER(14,2)  NOT NULL,   -- bbl
    oil_price       NUMBER(10,2)  NOT NULL,   -- USD per bbl
    operating_cost  NUMBER(14,2)  DEFAULT 0 NOT NULL, -- USD
    downtime_hours  NUMBER(4,1)   DEFAULT 0,
    loss_category   VARCHAR2(30),             -- recorded by the user; never inferred
    notes           VARCHAR2(500),
    created_at      TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    updated_at      TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE pp_targets (
    id               NUMBER        GENERATED BY DEFAULT ON NULL AS IDENTITY,
    user_id          NUMBER        NOT NULL,
    well_id          NUMBER        NOT NULL,
    daily_target_oil NUMBER(14,2)  NOT NULL,  -- bbl per day
    start_date       DATE          NOT NULL,
    end_date         DATE          NOT NULL,
    notes            VARCHAR2(300),
    created_at       TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    updated_at       TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE pp_alerts (
    id             NUMBER        GENERATED BY DEFAULT ON NULL AS IDENTITY,
    user_id        NUMBER        NOT NULL,
    well_id        NUMBER,
    record_id      NUMBER,
    rule_code      VARCHAR2(30)  NOT NULL,
    severity       VARCHAR2(10)  NOT NULL,
    message        VARCHAR2(300) NOT NULL,
    trigger_reason VARCHAR2(500) NOT NULL,
    alert_date     DATE          NOT NULL,
    status         VARCHAR2(15)  DEFAULT 'NEW' NOT NULL,
    dedupe_key     VARCHAR2(120) NOT NULL,
    created_at     TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    updated_at     TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL
);
